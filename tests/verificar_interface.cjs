const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('assert/strict');
const base = require('path').resolve(__dirname, '..');
(async () => {
  const config = JSON.parse(fs.readFileSync(process.env.REDE_ABERTA_CONFIG || `${base}/dados/app.json`));
  const url = `http://127.0.0.1:${config.porta}`;
  const browser = await chromium.launch({headless:true});
  const ctx = await browser.newContext({viewport:{width:1440,height:1000}});
  const pedidosComparacao = [];
  ctx.on('request', request => {
    if (request.method() === 'POST' && request.url().endsWith('/api/acao') && request.postDataJSON()?.acao === 'mostrar_comparacao') pedidosComparacao.push(request);
  });
  ctx.setDefaultTimeout(10000);
  const page = await ctx.newPage();
  const erros = [];
  page.on('pageerror', e => erros.push(e.message));
  await page.goto(`${url}/#sessao=${config.token}`);
  await page.waitForFunction(() => !document.querySelector('#mensagem').textContent.includes('Conectando'));
  const inicial = await page.evaluate(async () => await fetch('/api/estado').then(r=>r.json()));
  assert.ok(!inicial.ativo && !inicial.limpeza_pendente, 'Encerre a atividade ou use um servidor de teste isolado.');
  assert.equal(await page.locator('#iniciar').isEnabled(), true);
  if (process.env.VERIFICAR_WIFI === '1') {
    await page.getByRole('button', {name:'Verificar equipamento'}).click();
    await page.waitForFunction(() => document.querySelector('#mensagem').textContent.includes('Equipamento pronto'));
    assert.notEqual(await page.locator('#interface').inputValue(), '');
  }
  await page.getByRole('button', {name:'Iniciar ensaio', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#status-rede').textContent === 'Ensaio ativo');
  await page.getByRole('button', {name:'Simular aparelho', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#observados').textContent === '1');
  await page.getByRole('button', {name:'Simular envio', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#envios').textContent === '1');
  const popupPromise = page.waitForEvent('popup');
  await page.locator('#abrir-telao').click();
  const projetor = await popupPromise;
  projetor.on('pageerror', e => erros.push(e.message));
  await projetor.waitForFunction(() => typeof SLIDES !== 'undefined');
  assert.equal(new URL(projetor.url()).pathname, '/apresentacao');
  assert.equal(await projetor.evaluate(() => SLIDES.length), 37);
  const apresentador = page.frames().find(frame => frame.name() === 'palestrante-inclusao');
  assert.ok(apresentador, 'O painel deve incluir o modo palestrante.');
  await apresentador.waitForFunction(() => document.documentElement.classList.contains('palestrante'));
  // A posição agora pertence ao servidor e sobrevive ao recarregamento das janelas.
  await page.evaluate(() => fetch('/api/apresentacao', {method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify({indice:0})}));
  await projetor.waitForFunction(() => location.hash === '#1');
  await apresentador.waitForFunction(() => location.hash === '#1');
  await projetor.keyboard.press('ArrowRight');
  await apresentador.waitForFunction(() => location.hash === '#2');
  await page.keyboard.press('Home');
  await projetor.waitForFunction(() => location.hash === '#1');
  const primeiraDemo = await projetor.evaluate(() => SLIDES.findIndex(slide => slide.demo));
  assert.ok(primeiraDemo > 0);
  for (let i = 0; i < primeiraDemo; i++) await projetor.keyboard.press('ArrowRight');
  await projetor.waitForFunction(() => {
    const quadro = document.querySelector('#telao-vivo');
    return !quadro.hidden && quadro.contentDocument?.querySelector('#modo-telao')?.textContent.includes('DADOS FICTÍCIOS');
  });
  const telao = await (await projetor.$('#telao-vivo')).contentFrame();
  assert.ok(telao, 'A demonstração deve mostrar o telão ao vivo dentro da apresentação.');
  await projetor.setViewportSize({width:1280,height:720});
  await projetor.locator('#exibir-demo').waitFor({state:'visible'});
  assert.equal(await apresentador.locator('.controles-paineis [data-painel="comparacao"]').isDisabled(), true);
  await projetor.locator('#exibir-demo summary').click();
  await projetor.locator('.menu-demo [data-painel="dados"]').click();
  await projetor.locator('#confirmar-exibicao button[value="cancelar"]').click();
  assert.equal(await telao.locator('#dados-telao').isHidden(), true);
  await page.locator('#revelar').click();
  await page.locator('#confirmacao button[value="cancelar"]').click();
  assert.equal(await telao.locator('#dados-telao').isHidden(), true);
  await page.locator('#revelar').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await telao.waitForFunction(() => !document.querySelector('#dados-telao').hidden);
  assert.match(await telao.locator('#registros').innerText(), /Visitante 1/);
  await projetor.screenshot({path:'/tmp/rede-aberta-resultados.png'});
  await page.locator('#proximo').click();
  await telao.waitForFunction(() => document.querySelector('#passo-telao').textContent === '2 / 7');
  assert.equal(await telao.locator('#dados-telao').isHidden(), true);
  assert.equal(await telao.locator('#registros').innerText(), '');
  for(let i=0; i<7; i++) {
    await page.getByRole('button', {name:new RegExp(`^Etapa ${i+1}:`)}).click();
    await telao.waitForFunction((n) => document.querySelector('#passo-telao').textContent === `${n+1} / 7`, i);
    const medidas = await telao.evaluate(() => {
      const palco = document.querySelector('#palco');
      const corpo = document.querySelector('#corpo-telao').getBoundingClientRect();
      const rodape = document.querySelector('.slide-footer').getBoundingClientRect();
      return {largura:palco.clientWidth, altura:palco.clientHeight, fim:corpo.bottom, rodape:rodape.top};
    });
    assert.equal(medidas.largura/medidas.altura,16/9);
    assert.ok(medidas.fim <= medidas.rodape, `Slide ${i+1} sobrepõe rodapé: ${JSON.stringify(medidas)}`);
    if(i===1) await projetor.screenshot({path:'/tmp/rede-aberta-telao.png'});
  }
  // O laboratório usa conexões reais mesmo dentro de um ensaio do roteiro.
  await page.locator('#preparar-comparacao').click();
  await page.waitForFunction(() => document.querySelector('#status-comparacao').textContent.includes('Pronta no notebook'));
  await page.locator('#enviar-notebook').click();
  await page.locator('#confirmacao button[value="cancelar"]').click();
  assert.equal(await page.locator('#total-comparacao').textContent(), '0 envios nesta comparação');
  await page.locator('#enviar-notebook').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await page.waitForFunction(() => document.querySelector('#total-comparacao').textContent === '2 envios nesta comparação');
  assert.match(await page.locator('#resultados-comparacao').innerText(), /Texto encontrado nos bytes/);
  assert.match(await page.locator('#resultados-comparacao').innerText(), /TLSv1\.[23]/);
  const formPromise = page.waitForEvent('popup');
  await page.locator('#url-comparacao-http').click();
  const formulario = await formPromise;
  await formulario.waitForLoadState();
  assert.equal(new URL(formulario.url()).hostname, 'localhost');
  assert.ok(!(await ctx.cookies(formulario.url())).some(cookie => cookie.name === 'rede_sessao'), 'O formulário não deve receber o cookie do painel.');
  await formulario.locator('#mensagem').fill('OLA_TURMA');
  await formulario.locator('input[name="concordo"]').check();
  await formulario.getByRole('button', {name:'Enviar por HTTP', exact:true}).click();
  await formulario.getByRole('status').waitFor();
  await page.waitForFunction(() => document.querySelector('#total-comparacao').textContent === '3 envios nesta comparação');
  await projetor.locator('#exibir-demo summary').click();
  await projetor.locator('.menu-demo [data-painel="comparacao"]').click();
  await projetor.locator('#confirmar-exibicao button[value="cancelar"]').click();
  assert.equal(await telao.locator('#comparacao-telao').isHidden(), true);
  const pedidosAntes = pedidosComparacao.length;
  await projetor.locator('#exibir-demo summary').click();
  await projetor.locator('.menu-demo [data-painel="comparacao"]').click();
  await projetor.locator('#confirmar-exibicao button[value="confirmar"]').click();
  await telao.waitForFunction(() => !document.querySelector('#comparacao-telao').hidden);
  assert.match(await telao.locator('#modo-telao').innerText(), /COMPARAÇÃO REAL/);
  assert.match(await telao.locator('#quadros-telao').innerText(), /OLA_TURMA/);
  assert.equal(pedidosComparacao.length, pedidosAntes + 1, 'Um clique deve produzir uma única solicitação mesmo com palestrante e projetor sincronizados.');
  await apresentador.waitForFunction(() => document.querySelector('.controles-paineis [data-painel="comparacao"]').getAttribute('aria-pressed') === 'true');
  await page.keyboard.press('c');
  await telao.waitForFunction(() => document.querySelector('#comparacao-telao').hidden);
  await page.locator('#palestrante').scrollIntoViewIfNeeded();
  await apresentador.locator('.controles-paineis [data-painel="comparacao"]').click();
  await apresentador.locator('#confirmar-exibicao button[value="confirmar"]').click();
  await telao.waitForFunction(() => !document.querySelector('#comparacao-telao').hidden);
  await page.locator('#palestrante').scrollIntoViewIfNeeded();
  await apresentador.locator('.controles-paineis [data-painel="dados"]').click();
  await apresentador.locator('#confirmar-exibicao button[value="confirmar"]').click();
  await telao.waitForFunction(() => !document.querySelector('#dados-telao').hidden && document.querySelector('#comparacao-telao').hidden);
  await page.waitForFunction(() => document.querySelector('#projetar-comparacao').textContent.startsWith('Mostrar'));
  await page.locator('#projetar-comparacao').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await telao.waitForFunction(() => !document.querySelector('#comparacao-telao').hidden && document.querySelector('#dados-telao').hidden);
  await projetor.screenshot({path:'/tmp/rede-aberta-https.png'});
  assert.ok(await telao.evaluate(() => document.querySelector('.conclusao-comparacao').getBoundingClientRect().bottom < document.querySelector('.slide-footer').getBoundingClientRect().top));
  await page.getByRole('button', {name:/^Etapa 1:/}).click();
  await telao.waitForFunction(() => document.querySelector('#comparacao-telao').hidden);
  assert.equal(await telao.locator('#quadros-telao').innerText(), '');
  await page.locator('#encerrar-comparacao').click();
  await page.waitForFunction(() => !document.querySelector('#excluir-comparacao').disabled);
  await page.locator('#excluir-comparacao').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await page.waitForFunction(() => document.querySelector('#total-comparacao').textContent === '0 envios nesta comparação');
  await formulario.close();
  await page.screenshot({path:'/tmp/rede-aberta-painel.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({path:'/tmp/rede-aberta-mobile.png',fullPage:true});
  await projetor.setViewportSize({width:390,height:844});
  assert.equal(await telao.evaluate(() => document.querySelector('#palco').clientWidth),1920);
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button', {name:'Encerrar dinâmica', exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#status-rede').textContent === 'Parada');
  await page.locator('#excluir').click();
  await page.locator('#confirmacao button[value="confirmar"]').click();
  await page.waitForFunction(() => document.querySelector('#envios').textContent === '0');
  // O mesmo controle também funciona ao abrir o arquivo independente, com exemplos rotulados.
  const independente = await browser.newPage({viewport:{width:1280,height:720}});
  independente.on('pageerror', e => erros.push(e.message));
  await independente.route('https://**/*', route => route.abort());
  await independente.goto(require('url').pathToFileURL(`${base}/docs/apresentacao_completa.html`).href);
  await independente.waitForFunction(() => typeof SLIDES !== 'undefined');
  for (let i = 0; i < primeiraDemo; i++) await independente.keyboard.press('ArrowRight');
  await independente.locator('#exibir-demo summary').click();
  await independente.locator('.menu-demo [data-painel="comparacao"]').click();
  assert.equal(await independente.locator('#comparacao-telao').isVisible(), true);
  assert.match(await independente.locator('#comparacao-telao .dados-titulo').innerText(), /FICTÍCIO/);
  await independente.keyboard.press('d');
  assert.equal(await independente.locator('#dados-telao').isVisible(), true);
  assert.equal(await independente.locator('#comparacao-telao').isHidden(), true);
  await independente.keyboard.press('ArrowRight');
  assert.equal(await independente.locator('#dados-telao').isHidden(), true);
  await independente.close();
  const previa = await browser.newPage({viewport:{width:1280,height:720}});
  previa.on('pageerror', e => erros.push(e.message));
  await previa.route('https://**/*', route => route.abort());
  await previa.goto(require('url').pathToFileURL(`${base}/docs/previa_telao.html`).href);
  await previa.locator('#mostrar-comparacao').click();
  assert.equal(await previa.locator('#comparacao-telao').isVisible(), true);
  await previa.locator('#mostrar-dados').click();
  assert.equal(await previa.locator('#comparacao-telao').isHidden(), true);
  assert.equal(await previa.locator('#dados-telao').isVisible(), true);
  await previa.keyboard.press('ArrowRight');
  assert.equal(await previa.locator('#dados-telao').isHidden(), true);
  await previa.close();
  assert.deepEqual(erros, []);
  const requisicoes = await page.evaluate(async () => {
    const a = await fetch('/api/telao').then(r=>r.json());
    return {detalhes:'registros' in a, ativo:a.ativo};
  });
  assert.equal(requisicoes.detalhes,false);
  assert.equal(requisicoes.ativo,false);
  console.log('OK: apresentação com 37 slides, sincronização do palestrante e projetor, demonstração embutida, navegação, ensaio, aparelho e envio simulados, popup, confirmação/cancelamento, revelação/ocultação, 7 slides sem sobreposição, tela móvel, HTTP/HTTPS reais pelo notebook, formulário do usuário, isolamento do cookie, projeção por botão no slide, controles do palestrante, teclas C/D, exemplos independentes, encerramento e exclusão. Sem erros JavaScript.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
