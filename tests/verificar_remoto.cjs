// Execute somente com um app de teste isolado, como a verificação principal.
const {chromium} = require('playwright');
const fs = require('fs');
const assert = require('assert/strict');
const base = require('path').resolve(__dirname, '..');
(async () => {
  const config = JSON.parse(fs.readFileSync(process.env.REDE_ABERTA_CONFIG || `${base}/dados/app.json`));
  const url = `http://127.0.0.1:${config.porta}`;
  const browser = await chromium.launch({headless: true});
  try {
    const equipe = await browser.newContext({viewport: {width: 1440, height: 1000}});
    await equipe.route('https://**/*', route => route.abort());
    equipe.setDefaultTimeout(10000);
    const page = await equipe.newPage();
    const erros = [];
    page.on('pageerror', e => erros.push(e.message));
    await page.goto(`${url}/#sessao=${config.token}`);
    await page.waitForFunction(() => !document.querySelector('#mensagem').textContent.includes('Conectando'));
    const inicial = await page.evaluate(() => fetch('/api/estado').then(r => r.json()));
    assert.ok(!inicial.ativo && !inicial.limpeza_pendente, 'Use um servidor de teste isolado.');
    const acao = async (acao, dados = {}) => {
      const resposta = await page.evaluate(async dados => {
        for (let tentativa = 0; tentativa < 30; tentativa++) {
          const r = await fetch('/api/acao', {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify(dados)});
          const e = await r.json();
          if (r.status !== 409 || !e.erro?.includes('Aguarde')) return r.status;
          await new Promise(resolve => setTimeout(resolve, 100));
        }
        return 409;
      }, {acao, ...dados});
      assert.equal(resposta, 202);
      await page.waitForFunction(async () => !(await fetch('/api/estado').then(r => r.json())).ocupado);
    };
    const slide = async indice => {
      await page.evaluate(indice => fetch('/api/apresentacao', {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({indice})}), indice);
    };
    await acao('iniciar', {modo: 'ensaio'});
    await acao('simular_envio');
    await acao('simular_aparelho');
    const popup = page.waitForEvent('popup');
    await page.locator('#abrir-telao').click();
    const projetor = await popup;
    projetor.on('pageerror', e => erros.push(e.message));
    const palestrante = page.frames().find(f => f.name() === 'palestrante-inclusao');
    await projetor.waitForFunction(() => typeof SLIDES !== 'undefined');
    await slide(0);
    await projetor.waitForFunction(() => location.hash === '#1');
    await page.locator('#remoto-ativar').click();
    await page.locator('#remoto-acesso').waitFor({state: 'visible'});
    const endereco = await page.locator('#remoto-url').innerText();
    const codigo = await page.locator('#remoto-codigo').innerText();
    assert.match(codigo, /^\d{6}$/);
    assert.ok(await page.locator('#remoto-qr').evaluate(img => img.complete && img.naturalWidth > 0));
    const celular = await browser.newContext({viewport: {width: 390, height: 844}, isMobile: true, hasTouch: true});
    celular.setDefaultTimeout(10000);
    const telefone = await celular.newPage();
    telefone.on('pageerror', e => erros.push(e.message));
    await telefone.goto(endereco);
    await telefone.locator('#pareamento').waitFor({state: 'visible'});
    assert.equal((await celular.request.get(`${endereco}/api/estado`)).status(), 401);
    await telefone.locator('#codigo').fill(codigo);
    await telefone.getByRole('button', {name: 'Conectar controle'}).click();
    await telefone.locator('#controle').waitFor({state: 'visible'});
    await telefone.waitForFunction(() => document.querySelector('#numero').textContent === 'Slide 1 de 37');
    await telefone.locator('#avancar').click();
    await projetor.waitForFunction(() => location.hash === '#2');
    await palestrante.waitForFunction(() => location.hash === '#2');
    await projetor.keyboard.press('ArrowRight');
    await telefone.waitForFunction(() => document.querySelector('#numero').textContent === 'Slide 3 de 37');
    await telefone.locator('#voltar').click();
    await projetor.waitForFunction(() => location.hash === '#2');
    const demo = await projetor.evaluate(() => SLIDES.findIndex(s => s.demo));
    await slide(demo);
    await projetor.waitForFunction(n => location.hash === `#${n+1}`, demo);
    await telefone.locator('#paineis').waitFor({state: 'visible'});
    assert.equal(await telefone.locator('#comparacao').isDisabled(), true);
    await telefone.locator('#dados').click();
    await telefone.locator('#confirmacao button[value="cancelar"]').click();
    const telao = await (await projetor.$('#telao-vivo')).contentFrame();
    assert.ok(await telao.locator('#dados-telao').isHidden());
    await telefone.locator('#dados').click();
    await telefone.locator('#confirmacao button[value="confirmar"]').click();
    await telao.waitForFunction(() => !document.querySelector('#dados-telao').hidden);
    const remoto = await (await celular.request.get(`${endereco}/api/estado`)).json();
    for (const campo of ['registros', 'vizinhos', 'token', 'codigo']) assert.ok(!(campo in remoto));
    await acao('preparar_comparacao');
    await acao('enviar_notebook', {confirmar: true, mensagem: 'TESTE_CONTROLE'});
    await telefone.locator('#comparacao').click();
    await telefone.locator('#confirmacao button[value="confirmar"]').click();
    await telao.waitForFunction(() => !document.querySelector('#comparacao-telao').hidden);
    assert.ok(await telao.locator('#dados-telao').isHidden());
    await telefone.locator('#dados').click();
    await slide(demo + 1);
    await telefone.waitForFunction(n => document.querySelector('#numero').textContent === `Slide ${n+2} de 37`, demo);
    await telefone.locator('#confirmacao button[value="confirmar"]').click();
    await telefone.locator('#erro').waitFor({state: 'visible'});
    assert.match(await telefone.locator('#erro').innerText(), /slide mudou/i);
    assert.ok(await telao.locator('#dados-telao').isHidden());
    assert.equal(await telefone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await telefone.screenshot({path: '/tmp/rede-aberta-celular.png', fullPage: true});
    await page.locator('#remoto-renovar').click();
    await telefone.locator('#pareamento').waitFor({state: 'visible'});
    const novo = await page.locator('#remoto-codigo').innerText();
    assert.match(novo, /^\d{6}$/);
    await telefone.locator('#codigo').fill(novo);
    await telefone.getByRole('button', {name: 'Conectar controle'}).click();
    await telefone.locator('#controle').waitFor({state: 'visible'});
    await page.locator('#remoto-desativar').click();
    await page.waitForFunction(async () => !(await fetch('/api/estado').then(r => r.json())).remoto.ativo);
    await acao('encerrar');
    await acao('excluir', {confirmar: true});
    await acao('excluir_comparacao', {confirmar: true});
    assert.deepEqual(erros, []);
    console.log('OK: celular independente, QR local, código único, navegação dos 37 slides, sincronização notebook/projetor, confirmação/cancelamento, MAC/mensagens e HTTP/HTTPS, proteção contra confirmação em slide antigo, rotação e desativação. Sem erros JavaScript.');
  } finally { await browser.close(); }
})().catch(erro => {console.error(erro); process.exit(1);});
